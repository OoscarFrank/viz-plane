#!/usr/bin/env python3
"""Generates the airport table (ICAO -> IATA, position, city) used to resolve hexdb.io routes.

Source: OurAirports (public domain), large and medium airports with an ICAO code.
City names are shown on screen: common ones are translated to French, and
characters missing from the fonts (outside Latin-1) are transliterated.
Usage: python3 tools/gen_airports.py
"""
import csv, io, unicodedata, urllib.request
from pathlib import Path

URL = "https://davidmegginson.github.io/ourairports-data/airports.csv"
OUT = Path(__file__).resolve().parent.parent / "components" / "radar_app" / "assets" / "airports.c"

FRENCH = {
    "Geneva": "Genève", "London": "Londres", "Brussels": "Bruxelles", "Vienna": "Vienne",
    "Venice": "Venise", "Lisbon": "Lisbonne", "Seville": "Séville", "Barcelona": "Barcelone",
    "Copenhagen": "Copenhague", "Athens": "Athènes", "Frankfurt am Main": "Francfort",
    "Frankfurt": "Francfort", "Hamburg": "Hambourg", "Warsaw": "Varsovie", "Moscow": "Moscou",
    "Cairo": "Le Caire", "Edinburgh": "Édimbourg", "Bucharest": "Bucarest", "Prague": "Prague",
    "Munich": "Munich", "Cologne": "Cologne", "Nuremberg": "Nuremberg", "Dusseldorf": "Düsseldorf",
    "Düsseldorf": "Düsseldorf", "Zurich": "Zurich", "Palma De Mallorca": "Palma",
    "Palma de Mallorca": "Palma", "Valletta": "Malte", "Luqa": "Malte", "Larnaca": "Larnaca",
    "Tel Aviv": "Tel Aviv", "Antalya": "Antalya", "Istanbul": "Istanbul", "Algiers": "Alger",
    "Tunis": "Tunis", "Casablanca": "Casablanca", "Marrakech": "Marrakech", "Dubai": "Dubaï",
    "Doha": "Doha", "Bangkok": "Bangkok", "Singapore": "Singapour", "Beijing": "Pékin",
    "New York": "New York", "Montreal": "Montréal", "Mexico City": "Mexico",
}
# Codes used by route databases for EuroAirport besides LFSB
ALIASES = {"LSZM": "LFSB"}
OVERRIDE_CITY = {"LFSB": "Bâle-Mulhouse"}


def latin1(s):
    out = []
    for ch in s:
        if ord(ch) <= 0xFF:
            out.append(ch)
        else:
            out.append("".join(c for c in unicodedata.normalize("NFKD", ch) if ord(c) < 0x80))
    return "".join(out)


def clip(s, n):
    """Cut to at most n bytes of UTF-8 without splitting a character."""
    b = s.encode()
    while len(b) > n:
        s = s[:-1]
        b = s.encode()
    return s


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


rows = csv.DictReader(io.StringIO(urllib.request.urlopen(URL).read().decode("utf-8")))
ap = {}
for r in rows:
    icao = r["icao_code"] or (r["ident"] if len(r["ident"]) == 4 and r["ident"].isalpha() else "")
    if r["type"] not in ("large_airport", "medium_airport") or not icao:
        continue
    city = OVERRIDE_CITY.get(icao) or FRENCH.get(r["municipality"], r["municipality"]) or r["name"]
    ap[icao] = (r["iata_code"], float(r["latitude_deg"]), float(r["longitude_deg"]), clip(latin1(city), 23))
for alias, real in ALIASES.items():
    ap[alias] = ap[real]

lines = [
    "/* Generated by tools/gen_airports.py from OurAirports (public domain). Do not edit. */",
    '#include "airports.h"',
    "",
    "const airport_t airports[] = {",
]
for icao in sorted(ap):
    iata, lat, lon, city = ap[icao]
    lines.append(f'    {{"{icao}", "{iata}", {lat:.4f}f, {lon:.4f}f, {cstr(city)}}},')
lines += ["};", "const int airports_n = sizeof airports / sizeof airports[0];", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(ap)} airports -> {OUT}")
